import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

// Mutates only synthetic demonstration records. Intended for an authorized demo.
const base=process.env.BASE_URL;
if(!base)throw Error('BASE_URL required');
const request=async(method,path,body,status=200,extra={})=>{
  const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...extra},body:body===undefined?undefined:JSON.stringify(body),signal:AbortSignal.timeout(20000)});
  assert.equal(r.status,status,`${method} ${path}`);
  return r.headers.get('content-type')?.includes('application/json')?r.json():r.text();
};
const state=()=>request('GET','/api/state');
const initial=await state();assert.equal(initial.storageMode,'postgres');assert.equal(initial.resetProtected,true);
await request('POST','/api/reset',{},403);
await request('POST','/api/tasks',{},403,{Origin:'https://foreign.example.test'});
const person=await request('POST','/api/people',{name:'Synthetic Production QA',email:'production-qa@example.test',role:'Synthetic Operations QA',start_date:initial.today,systems:['Synthetic QA System'],device:'Synthetic QA laptop'});
await request('POST',`/api/people/${person.id}/lifecycle`,{action:'activate'},400);
let s=await state();
assert.equal(s.evidence.find(e=>e.id===1).health,'source_changed');
assert.equal((await request('GET','/api/reviews/1/package')).approved.length,0);
const grant=s.access.find(a=>a.person_id===person.id),device=s.devices.find(d=>d.person_id===person.id);
await request('POST',`/api/access/${grant.id}`,{note:'Synthetic production QA grant record'});
await request('POST',`/api/devices/${device.id}`,{asset_tag:'DEMO-PROD-QA',note:'Synthetic production QA custody record'});
await request('POST',`/api/people/${person.id}/lifecycle`,{action:'activate'});
assert.equal((await state()).people.find(p=>p.id===person.id).status,'active');
const review=await request('POST','/api/reviews',{customer:'Synthetic Production QA Review',deadline:initial.today});
await request('POST',`/api/reviews/${review.id}/import`,{csv:'question\n"=QA synthetic access question, with a comma"'});
let q=(await state()).questions.find(q=>q.review_id===review.id);
await request('PATCH',`/api/questions/${q.id}`,{control_id:1,evidence_id:2,draft:'Synthetic mismatch must be denied'},400);
await request('PATCH',`/api/questions/${q.id}`,{control_id:1,evidence_id:1,draft:'=QA synthetic manually reviewed demonstration answer'});
await request('POST',`/api/questions/${q.id}/approve`,{reviewer:'Synthetic QA Reviewer'},400);
await request('POST','/api/evidence/1/approve',{reviewer:'Synthetic Evidence QA'},400);
const ev=(await state()).evidence.find(e=>e.id===1);
await request('PATCH','/api/evidence/1',{reference:ev.reference,owner:ev.owner,review_due:ev.review_due,note:'Synthetic stale reference'},400);
await request('PATCH','/api/evidence/1',{reference:`DEMO-PRODUCTION-QA-${Date.now()}`,owner:ev.owner,review_due:ev.review_due,note:'Synthetic revised register source'});
await request('POST',`/api/questions/${q.id}/approve`,{reviewer:'Synthetic QA Reviewer'},400);
await request('POST','/api/evidence/1/approve',{reviewer:'Synthetic Evidence QA'});
assert.equal((await request('GET',`/api/reviews/${review.id}/package`)).approved.length,0);
await request('POST',`/api/questions/${q.id}/approve`,{reviewer:'Synthetic QA Reviewer'});
assert.equal((await request('GET',`/api/reviews/${review.id}/package`)).approved.length,1);
const csv=await request('GET',`/api/reviews/${review.id}/export`);
assert.match(csv,/"'=QA synthetic access question/);assert.match(csv,/"'=QA synthetic manually reviewed/);
await request('PATCH',`/api/questions/${q.id}`,{control_id:1,evidence_id:1,draft:'Synthetic revised draft needs new review'});
assert.equal((await request('GET',`/api/reviews/${review.id}/package`)).approved.length,0);
await request('POST',`/api/questions/${q.id}/approve`,{reviewer:'Synthetic QA Reviewer'});
await request('POST',`/api/people/${person.id}/lifecycle`,{action:'start_offboarding'});
await request('POST',`/api/people/${person.id}/lifecycle`,{action:'complete_offboarding'},400);
await request('POST',`/api/access/${grant.id}`,{note:'Synthetic production QA revocation record'});
await request('POST',`/api/devices/${device.id}`,{note:'Synthetic production QA physical return'});
await request('POST',`/api/people/${person.id}/lifecycle`,{action:'complete_offboarding'});
assert.equal((await request('GET',`/api/reviews/${review.id}/package`)).approved.length,0);
assert.doesNotMatch(await request('GET',`/api/reviews/${review.id}/export`),/Synthetic revised draft/);
const final=await state();assert.equal(final.people.find(p=>p.id===person.id).status,'offboarded');
assert.ok(final.history.some(h=>h.action==='OFFBOARDING_COMPLETED'&&h.entity_id===person.id));
assert.deepEqual(await state(),final);
await fs.mkdir('test-results',{recursive:true});
await fs.writeFile('test-results/before-redeploy.json',JSON.stringify(final));
console.log('PRODUCTION HTTP PASS: persisted lifecycle, denied gates, source invalidation, CSV import, matching evidence, fresh approvals, safe export, draft invalidation, offboarding, audit, reset/origin protection, repeated reads');
